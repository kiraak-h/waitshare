import path from "node:path"
import fs from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const Database = require("better-sqlite3")

const dataDir = process.env.DATA_DIR ?? path.resolve(import.meta.dirname, "../data")
const dbPath = process.env.WAITSHARE_DB ?? path.join(dataDir, "waitshare.db")
const outPath = process.argv[2]

if (!fs.existsSync(dbPath)) {
  console.error(`no database at ${dbPath}`)
  process.exit(1)
}

const db = new Database(dbPath, { readonly: true })

// table -> optional per-row transform to map SQLite storage into Postgres types
const BOOL_TABLES = new Set(["devs"])

const tables = [
  "devs",
  "device_keys",
  "sessions",
  "advertisers",
  "campaigns",
  "serves",
  "impressions",
  "fraud_events",
  "payouts",
  "update_manifests",
  "split_contract",
]

function literal(v) {
  if (v === null || v === undefined) return "NULL"
  if (typeof v === "number") return String(v)
  if (typeof v === "boolean") return v ? "true" : "false"
  const s = String(v).replaceAll("'", "''")
  return `'${s}'`
}

const lines = ["-- Generated by server/scripts/export-postgres.mjs", "BEGIN;"]

for (const t of tables) {
  const exists = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name=?").get(t)
  if (!exists) continue
  const rows = db.prepare(`SELECT * FROM ${t}`).all()
  if (rows.length === 0) continue
  const cols = Object.keys(rows[0])

  for (const row of rows) {
    let vals = cols.map((c) => row[c])
    if (BOOL_TABLES.has(t) && cols.includes("stripe_onboarded")) {
      vals = cols.map((c, i) => (c === "stripe_onboarded" ? (row[c] ? "true" : "false") : row[c]))
    }
    lines.push(
      `INSERT INTO ${t} (${cols.map((c) => `"${c}"`).join(", ")}) VALUES (${vals.map(literal).join(", ")});`
    )
  }
  console.error(`exported ${rows.length} rows from ${t}`)
}

lines.push("COMMIT;")

if (outPath) {
  fs.writeFileSync(outPath, lines.join("\n") + "\n")
  console.error(`wrote ${lines.length} statements to ${outPath}`)
} else {
  process.stdout.write(lines.join("\n") + "\n")
}
